// Concatenates migrations + seed into supabase/setup.sql for a one-paste setup
// in the Supabase SQL editor. Run: npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = "supabase/migrations";
const parts = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort().map((f) => `-- >>> ${f}\n${readFileSync(`${dir}/${f}`, "utf8")}`);
parts.push(`-- >>> seed.sql\n${readFileSync("supabase/seed.sql", "utf8")}`);
parts.push(`-- >>> content_professions.sql\n${readFileSync("supabase/content_professions.sql", "utf8")}`);
writeFileSync("supabase/setup.sql", `-- GENERATED by scripts/bundle-sql.mjs — do not edit by hand.\n-- Paste into Supabase → SQL Editor → Run, once, on a fresh project.\n-- Runs as ONE transaction: if anything fails, nothing is applied.\n-- If a previous attempt left pieces behind, run supabase/reset.sql first.\n\nbegin;\n\n${parts.join("\n\n")}\n\ncommit;\n`);
console.log("wrote supabase/setup.sql");
